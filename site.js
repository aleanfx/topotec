const getDictionary = (lang) => I18N[lang] || I18N[DEFAULT_LANG];

const formatTemplate = (template, data) =>
  template.replace(/\{(\w+)\}/g, (_, key) => data[key] || "-");

const updateLangToggle = (lang) => {
  document.querySelectorAll("[data-lang-toggle]").forEach((toggle) => {
    toggle.querySelectorAll("span").forEach((span) => {
      const isActive = span.dataset.lang === lang;
      span.classList.toggle("active", isActive);
    });
  });
};

const applyTranslations = (lang) => {
  const dict = getDictionary(lang);
  document.documentElement.lang = lang;
  document.body.dataset.lang = lang;
  const titleKey = document.body.dataset.pageTitle;
  if (titleKey && dict[titleKey]) {
    document.title = dict[titleKey].replace(/<[^>]*>/g, "");
  }
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (dict[key]) {
      el.innerHTML = dict[key];
    }
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (dict[key]) {
      el.setAttribute("placeholder", dict[key]);
    }
  });
  updateLangToggle(lang);
};

const initLanguage = () => {
  const stored = localStorage.getItem("lang");
  const lang = stored && I18N[stored] ? stored : DEFAULT_LANG;
  applyTranslations(lang);
  document.querySelectorAll("[data-lang-toggle]").forEach((toggle) => {
    toggle.addEventListener("click", () => {
      const current = document.documentElement.lang || DEFAULT_LANG;
      const next = current === "es" ? "en" : "es";
      localStorage.setItem("lang", next);
      applyTranslations(next);
    });
  });
};

