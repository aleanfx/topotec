const initModals = () => {
  const openButtons = document.querySelectorAll("[data-modal-open]");
  const closeButtons = document.querySelectorAll("[data-modal-close]");
  const modals = document.querySelectorAll("[data-modal]");
  if (!modals.length) return;
  let lastFocused = null;

  const openDialog = (modal, trigger) => {
    lastFocused = trigger || document.activeElement;
    modal.classList.add("is-open");
    modal.setAttribute("aria-hidden", "false");
    document.body.classList.add("modal-open");
    const focusTarget = modal.querySelector("[data-modal-close]");
    if (focusTarget) focusTarget.focus();
  };

  const closeDialog = (modal) => {
    modal.classList.remove("is-open");
    modal.setAttribute("aria-hidden", "true");
    document.body.classList.remove("modal-open");
    if (lastFocused && typeof lastFocused.focus === "function") {
      lastFocused.focus();
    }
  };

  openButtons.forEach((button) => {
    button.addEventListener("click", () => {
      const modalId = button.dataset.modalOpen;
      if (!modalId) return;
      const modal = document.getElementById(modalId);
      if (modal) openDialog(modal, button);
    });
  });

  closeButtons.forEach((button) => {
    button.addEventListener("click", () => {
      const modal = button.closest("[data-modal]");
      if (modal) closeDialog(modal);
    });
  });

  modals.forEach((modal) => {
    modal.addEventListener("click", (event) => {
      if (event.target === modal) {
        closeDialog(modal);
      }
    });
  });

  document.addEventListener("keydown", (event) => {
    if (event.key !== "Escape") return;
    const openModal = document.querySelector("[data-modal].is-open");
    if (openModal) closeDialog(openModal);
  });
};

